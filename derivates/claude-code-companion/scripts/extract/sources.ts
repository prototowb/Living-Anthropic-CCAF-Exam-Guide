// Source registry — the pipeline iterates over this array. Each entry
// pairs an authored source with the schema/few-shot bundle that extracts it
// and the typed module the UI will read.

import type { SourceDefinition } from './lib/types';
import {
  glossarySchema,
  glossaryDocumentSchema,
  GLOSSARY_SCHEMA_VERSION,
} from './schemas/glossary';
import {
  architectScenarioSchema,
  architectScenariosDocumentSchema,
  ARCHITECT_SCENARIOS_SCHEMA_VERSION,
} from './schemas/architectScenarios';
import { GLOSSARY_FEWSHOT } from './fewShot/glossary';
import { ARCHITECT_SCENARIOS_FEWSHOT } from './fewShot/architectScenarios';
import type { FewShotExample } from './lib/types';

export interface SourceConfig extends SourceDefinition {
  /** Top-level (document) schema. Validates the whole adapter response. */
  documentSchema: Record<string, unknown>;
  /** Per-record schema. Useful for v0.3's retry-per-record loop. */
  recordSchema: Record<string, unknown>;
  fewShot: FewShotExample[];
  /** System prompt fragment passed to the adapter. */
  systemPrompt: string;
  /** TS module template — how the validated payload becomes a typed `_generated/*.ts` file. */
  emit: (validated: unknown) => string;
}

export const SOURCES: SourceConfig[] = [
  {
    id: 'glossary',
    sourcePath: 'docs/extraction-sources/glossary.md',
    outputPath: 'src/data/_generated/glossary.ts',
    schemaVersion: GLOSSARY_SCHEMA_VERSION,
    label: 'Beginner glossary',
    documentSchema: glossaryDocumentSchema as unknown as Record<string, unknown>,
    recordSchema: glossarySchema as unknown as Record<string, unknown>,
    fewShot: GLOSSARY_FEWSHOT,
    systemPrompt:
      'You are a structured-data extractor. Read a markdown glossary and emit an object {entries: GlossaryEntry[]}. Beginner voice; one paragraph per definition; never invent terms.',
    emit(validated) {
      const payload = validated as { entries: unknown[] };
      return `// AUTO-GENERATED by \`npm run extract\`. Do not edit by hand.\n// Source: docs/extraction-sources/glossary.md\n// Schema version: ${GLOSSARY_SCHEMA_VERSION}\n\nimport type { GlossaryEntry } from '@/data/_generated/types';\n\nexport const glossary: GlossaryEntry[] = ${JSON.stringify(payload.entries, null, 2)};\n`;
    },
  },
  {
    id: 'architectScenarios',
    sourcePath: 'sprints/_exam-guide.txt',
    outputPath: 'src/data/_generated/architectScenarios.ts',
    schemaVersion: ARCHITECT_SCENARIOS_SCHEMA_VERSION,
    label: 'Architect Foundations — six exam scenarios',
    documentSchema: architectScenariosDocumentSchema as unknown as Record<string, unknown>,
    recordSchema: architectScenarioSchema as unknown as Record<string, unknown>,
    fewShot: ARCHITECT_SCENARIOS_FEWSHOT,
    systemPrompt:
      'You are a structured-data extractor. Read the Anthropic Architect Foundations exam-guide excerpt and emit {scenarios: ArchitectScenario[]} with all six scenarios verbatim. Preserve names and primary-domain wording exactly.',
    emit(validated) {
      const payload = validated as { scenarios: unknown[] };
      return `// AUTO-GENERATED by \`npm run extract\`. Do not edit by hand.\n// Source: sprints/_exam-guide.txt (verbatim from the local Anthropic exam-guide PDF).\n// Schema version: ${ARCHITECT_SCENARIOS_SCHEMA_VERSION}\n\nimport type { ArchitectScenario } from '@/data/_generated/types';\n\nexport const architectScenarios: ArchitectScenario[] = ${JSON.stringify(payload.scenarios, null, 2)};\n`;
    },
  },
];
